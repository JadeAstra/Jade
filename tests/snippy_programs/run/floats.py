# Floats: their repr (the shortest that reads back), arithmetic, inf and nan, comparisons with ints.
print(0.1, 0.2, 0.1 + 0.2, 1.0, 1.5e300, 1e-7, 3.14159, 2.0 ** 0.5, 1 / 7)
print(1e15, 1e16, 1e17, 123456789012345678.0, 0.0001, 0.00001, -0.0)
print(float("inf"), float("-inf"), float("nan"), float(" 1.5 "), float("1e3"), float("-1_0.5"))
inf = float("inf")
nan = float("nan")
print(inf > 1e308, -inf < 0, nan == nan, nan != nan, inf == inf, inf - inf)
print(7.5 // 2, 7.5 % 2, -7.5 // 2, -7.5 % 2, 7.5 % -2, divmod(7.5, 2), divmod(-7.5, 2))
print(1 == 1.0, 2 ** 53 == 2.0 ** 53, 2 ** 53 + 1 == 2.0 ** 53, 1 < 1.5, 3 >= 3.0)
print(round(2.675, 2), round(0.125, 2), round(1.5), round(-1.5), round(3.14159, 3), round(1e300, -300))
print(abs(-2.5), max(1, 2.5), min(-1.0, -1), sum([0.1] * 10), sum([1, 2.5, 3]))
print(int(2.9), int(-2.9), float(10), 10 / 4, 10 / 5, 7 / 2)
print((0.5).as_integer_ratio(), (0.1).as_integer_ratio(), (3.0).is_integer(), (3.5).is_integer())
